#include <iostream>
#include <vector>
#include <algorithm>


using namespace std;


    int a[100][100];   // баллы в клетках
    int d[100][100];   // записки: "отсюда до препода соберёшь максимум столько"

    int main() {
        int n, m;
        cin >> n >> m;                 // сколько строк и столбцов


        for (int i = 0; i < n; i++)
            for (int j = 0; j < m; j++)
                cin >> a[i][j];

       // пишем записки, начиная с препода и двигаясь к входу
        for (int i = n - 1; i >= 0; i--)
            for (int j = m - 1; j >= 0; j--) {
                if (i == n - 1 && j == m - 1)          // это сам препод
                    d[i][j] = a[i][j];
                else if (i == n - 1)                   // нижний ряд, можно только вправо
                    d[i][j] = a[i][j] + d[i][j + 1];
                else if (j == m - 1)                   // правый край, можно только вниз
                    d[i][j] = a[i][j] + d[i + 1][j];
                else if (d[i + 1][j] > d[i][j + 1])    // снизу записка больше
                    d[i][j] = a[i][j] + d[i + 1][j];
                else                                   // справа записка больше
                    d[i][j] = a[i][j] + d[i][j + 1];
            }


        int i = 0, j = 0;                  // стоим на входе
        cout << i << " " << j << endl;     // печатаем вход
        while (i != n - 1 || j != m - 1) { // пока не пришли к преподу
            if (i == n - 1) j++;                        // внизу, значит вправо
            else if (j == m - 1) i++;                   // справа край, значит вниз
            else if (d[i + 1][j] > d[i][j + 1]) i++;    // снизу записка больше, идём вниз
            else j++;                                   // иначе вправо
            cout << i << " " << j << endl;              // печатаем, куда встали
        }
    }

